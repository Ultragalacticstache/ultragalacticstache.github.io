  var STORAGE_KEY = "ugs-lang";
  var originals = new Map();

  function currentLang() {
    try { return localStorage.getItem(STORAGE_KEY) || "en"; } catch (e) { return "en"; }
  }

  function storeOriginal(el, kind, attr) {
    var mapKey = el;
    if (!originals.has(mapKey)) originals.set(mapKey, {});
    var rec = originals.get(mapKey);
    if (kind === "html" && rec.html === undefined) rec.html = el.innerHTML;
    if (kind === "attr" && rec.attrs === undefined) rec.attrs = {};
    if (kind === "attr" && rec.attrs[attr] === undefined) rec.attrs[attr] = el.getAttribute(attr);
  }

  function applyLang(lang) {
    var nodes = document.querySelectorAll("[data-i18n]");
    nodes.forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      storeOriginal(el, "html");
      if (lang === "ro" && I18N_RO[key] !== undefined) {
        el.innerHTML = I18N_RO[key];
      } else {
        el.innerHTML = originals.get(el).html;
      }
    });

    var attrNodes = document.querySelectorAll("[data-i18n-attr]");
    attrNodes.forEach(function (el) {
      var pairs = el.getAttribute("data-i18n-attr").split(";");
      pairs.forEach(function (pair) {
        var parts = pair.split(":");
        if (parts.length !== 2) return;
        var attr = parts[0].trim();
        var key = parts[1].trim();
        storeOriginal(el, "attr", attr);
        if (lang === "ro" && I18N_RO[key] !== undefined) {
          el.setAttribute(attr, I18N_RO[key]);
        } else {
          el.setAttribute(attr, originals.get(el).attrs[attr]);
        }
      });
    });

    document.documentElement.setAttribute("lang", lang === "ro" ? "ro" : "en");
    document.querySelectorAll("[data-lang-set]").forEach(function (btn) {
      var isActive = btn.getAttribute("data-lang-set") === lang;
      btn.setAttribute("aria-pressed", isActive ? "true" : "false");
    });

    var yearEl = document.querySelector("[data-year]");
    if (yearEl) yearEl.textContent = new Date().getFullYear();
  }

  function setLang(lang) {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    applyLang(lang);
  }

  document.addEventListener("DOMContentLoaded", function () {
    applyLang(currentLang());
    document.querySelectorAll("[data-lang-set]").forEach(function (btn) {
      btn.addEventListener("click", function () {
        setLang(btn.getAttribute("data-lang-set"));
      });
    });
  });
